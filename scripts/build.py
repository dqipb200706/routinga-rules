#!/usr/bin/env python3
"""Build RoutingA from pinned upstream snapshots; fail closed on invalid input."""
import concurrent.futures
import hashlib
import ipaddress
import json
import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / 'dist'
SOURCES = {
    'direct': ('Loyalsoldier/surge-rules', 'release', 'direct.txt', 1000),
    'proxy': ('Loyalsoldier/surge-rules', 'release', 'proxy.txt', 1000),
    'reject': ('Loyalsoldier/surge-rules', 'release', 'reject.txt', 1000),
    'private': ('Loyalsoldier/surge-rules', 'release', 'private.txt', 1),
    'ipv4': ('PaPerseller/chn-iplist', 'master', 'chnroute-ipv4.txt', 1000),
    'ipv6': ('PaPerseller/chn-iplist', 'master', 'chnroute-ipv6.txt', 100),
}

def fetch(url):
    req = urllib.request.Request(url, headers={'User-Agent': 'routinga-rules-builder'})
    with urllib.request.urlopen(req, timeout=60) as response:
        data = response.read(30_000_001)
    if len(data) > 30_000_000:
        raise ValueError('Source too large: ' + url)
    return data

def domains(text):
    result = set()
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith(('#', '//')):
            continue
        suffix = line.startswith('.')
        name = line.lstrip('.') if suffix else line
        if not re.fullmatch(r'[A-Za-z0-9_-]+(?:\.[A-Za-z0-9_-]+)*', name):
            raise ValueError('Invalid DOMAIN-SET entry: ' + line)
        result.add(('domain:' if suffix else 'full:') + name.lower())
    return result

def networks(text, version):
    result = set()
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith('#'):
            continue
        network = ipaddress.ip_network(line, strict=True)
        if network.version != version or network.prefixlen == 0 or network.is_multicast or network.is_loopback or network.is_link_local:
            raise ValueError('Invalid network: ' + line)
        result.add(str(network))
    return result

def render(entries, function, outbound):
    values = sorted(entries)
    lines = []
    for start in range(0, len(values), 100):
        batch = values[start:start + 100]
        if function == 'ip':
            batch = [json.dumps(v) if ':' in v else v for v in batch]
        lines.append(f'{function}(' + ', '.join(batch) + f') -> {outbound}')
    return lines

def build_rules(datasets, custom, mode):
    if mode not in ('blacklist', 'whitelist'):
        raise ValueError('Unknown mode: ' + mode)
    default = 'direct' if mode == 'blacklist' else 'proxy'
    lines = ['# Generated by scripts/build.py; do not edit.', f'default: {default}',
             f'# Policy: {mode}', '', '# LAN IPs always direct', 'ip(geoip:private) -> direct']
    lines += render(datasets['private'], 'domain', 'direct')
    for name, target in (('direct', 'direct'), ('proxy', 'proxy'), ('reject', 'block')):
        lines += ['', '# Personal ' + name] + render(custom[name], 'domain', target)
    lines += ['', '# Upstream reject'] + render(datasets['reject'], 'domain', 'block')
    if mode == 'blacklist':
        lines += ['', '# Upstream proxy'] + render(datasets['proxy'] - datasets['reject'], 'domain', 'proxy')
    else:
        lines += ['', '# Upstream direct'] + render(datasets['direct'] - datasets['reject'], 'domain', 'direct')
        lines += ['', '# Explicit mainland IPv4 / IPv6 CIDRs']
        lines += render(datasets['ipv4'] | datasets['ipv6'], 'ip', 'direct')
    return '\n'.join(lines) + '\n'


def main():
    pins = {}
    for repo, branch, _, _ in SOURCES.values():
        key = (repo, branch)
        if key not in pins:
            pins[key] = json.loads(fetch(f'https://api.github.com/repos/{repo}/commits/{branch}'))['sha']
    def download(item):
        name, (repo, branch, path, minimum) = item
        sha = pins[(repo, branch)]
        url = f'https://raw.githubusercontent.com/{repo}/{sha}/{path}'
        data = fetch(url)
        text = data.decode('utf-8-sig')
        values = networks(text, int(name[-1])) if name.startswith('ipv') else domains(text)
        if len(values) < minimum:
            raise ValueError(f'{name}: only {len(values)} entries, expected >= {minimum}')
        return name, values, {'repo': repo, 'commit': sha, 'url': url, 'sha256': hashlib.sha256(data).hexdigest(), 'count': len(values)}
    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
        results = list(pool.map(download, SOURCES.items()))
    datasets = {name: values for name, values, _ in results}
    manifest = {name: info for name, _, info in results}
    old_path = OUT / 'manifest.json'
    if old_path.exists():
        previous = json.loads(old_path.read_text())
        for name, info in manifest.items():
            old_count = previous['sources'].get(name, {}).get('count', 0)
            if old_count and not 0.7 <= info['count'] / old_count <= 1.5:
                raise ValueError(f'{name}: abnormal count change {old_count} -> {info["count"]}')
    custom = {}
    for name in ('direct', 'proxy', 'reject'):
        custom[name] = domains((ROOT / 'custom' / (name + '.txt')).read_text())
    for a, b in (('direct', 'proxy'), ('direct', 'reject'), ('proxy', 'reject')):
        if custom[a] & custom[b]:
            raise ValueError(f'Conflicting custom rules: {a}/{b}')
    # Each output only includes the categories relevant to its policy.
    # Personal exceptions are shared, with block > proxy > direct for overlaps.
    overlaps = {name: len(datasets[a] & datasets[b]) for name, a, b in (
        ('reject_proxy', 'reject', 'proxy'), ('reject_direct', 'reject', 'direct'), ('proxy_direct', 'proxy', 'direct'))}
    outputs = {
        'routingA-blacklist.txt': build_rules(datasets, custom, 'blacklist'),
        'routingA-whitelist.txt': build_rules(datasets, custom, 'whitelist'),
    }
    # Preserve the existing URL for users already consuming the direct-default policy.
    outputs['routingA.txt'] = outputs['routingA-blacklist.txt']
    output_hashes = {name: hashlib.sha256(text.encode()).hexdigest()
                     for name, text in outputs.items()}
    OUT.mkdir(exist_ok=True)
    # All retrieval and validation finishes before any output is replaced.
    payloads = {**outputs, 'manifest.json': json.dumps({
        'sources': manifest, 'duplicate_patterns': overlaps,
        'custom_counts': {k: len(v) for k, v in custom.items()},
        'outputs_sha256': output_hashes,
        'output_sha256': output_hashes['routingA.txt'],
    }, indent=2) + '\n'}
    for name, text in payloads.items():
        temp = OUT / (name + '.new')
        temp.write_text(text)
        temp.replace(OUT / name)
    print(json.dumps({'source_counts': {k: v['count'] for k, v in manifest.items()},
                      'output_bytes': {k: len(v.encode()) for k, v in outputs.items()},
                      'duplicate_patterns': overlaps}, indent=2))

if __name__ == '__main__':
    main()
